def glyph(c):
    rows = FONT_SRC[c].split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
    cols = [0]  # leading blank column (keeps first byte < 0x7F)
    for x in range(5):
        b = 0
        for y in range(7):
            if rows[y][x] == '#':
                b |= 1 << y
        cols.append(b)
    return bytes(cols)


def text_bytes(s):
    return b"".join(glyph(c) for c in s)


def render_preview(path):
    """Render the initial position the way ChDRAW should draw it (for design review)."""
    from PIL import Image
    W, H = 400, 240
    fb = [[0] * W for _ in range(H)]
    sp = sprite_list()
    start = ["RNBQKBNR", "PPPPPPPP"] + ["........"] * 4 + ["pppppppp", "rnbqkbnr"]
    for r in range(1, 9):
        for f in range(1, 9):
            ch = start[r - 1][f - 1]
            p = 0 if ch == '.' else (PTYPES.index(ch.upper()) + 1) * (1 if ch.isupper() else -1)
            dark = (r + f) % 2 == 0
            code = (p + 6) * 2 + dark
            if code not in sp:
                continue
            y = Y0 + (8 - r) * SQ
            x = X0 + (f - 1) * SQ
            for (j, a, bs) in strips(sp[code]):
                for i, b in enumerate(bs):
                    for k in range(8):
                        if b >> k & 1:
                            fb[y + j + k - 1][x + a + i - 1] = 1
    im = Image.new("1", (W, H), 1)
    for y in range(H):
        for x in range(W):
            if fb[y][x]:
                im.putpixel((x, y), 0)
    im = im.convert("L").resize((W * 2, H * 2), Image.NEAREST)
    im.save(path)


if __name__ == "__main__":
    render_preview("preview.png")
