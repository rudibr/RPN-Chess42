def grid(s):
    rows = [r for r in s.strip("\n").split("\n")]
    assert len(rows) == 20 and all(len(r) == 20 for r in rows), [len(r) for r in rows]
    return [[c == '#' for c in r] for r in rows]


def erode(g):
    h, w = len(g), len(g[0])
    out = [[False] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if g[y][x] and all(0 <= y + dy < h and 0 <= x + dx < w and g[y + dy][x + dx]
                               for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = True
    return out


def dilate(g, r=1):
    h, w = len(g), len(g[0])
    out = [[False] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if any(0 <= y + dy < h and 0 <= x + dx < w and g[y + dy][x + dx]
                   for dy in range(-r, r + 1) for dx in range(-r, r + 1)):
                out[y][x] = True
    return out


def blank(w=SQ, h=SQ):
    return [[False] * w for _ in range(h)]


def dots(x, y):
    return x % 2 == 0 and y % 2 == 0


def square_bitmap(piece, white, dark):
    """26x26 bitmap for one square."""
    img = blank()
    sil = None
    if piece:
        g = grid(PIECES[piece])
        sil = [[False] * SQ for _ in range(SQ)]
        for y in range(20):
            for x in range(20):
                sil[y + 3][x + 3] = g[y][x]
    if dark:
        mask = dilate(sil, 1) if sil else blank()
        for y in range(SQ):
            for x in range(SQ):
                if dots(x, y) and not mask[y][x]:
                    img[y][x] = True
    if sil:
        if white:
            inner = erode(sil)
            for y in range(SQ):
                for x in range(SQ):
                    if sil[y][x] and not inner[y][x]:
                        img[y][x] = True
        else:
            for y in range(SQ):
                for x in range(SQ):
                    if sil[y][x]:
                        img[y][x] = True
    return img


def frame_bitmap():
    img = blank()
    for i in range(SQ):
        for t in (0, 1, SQ - 2, SQ - 1):
            img[t][i] = img[i][t] = True
    return img


def corners_bitmap():
    img = blank()
    L = 7
    for i in range(L):
        for (cy, cx, sy, sx) in ((0, 0, 1, 1), (0, SQ - 1, 1, -1), (SQ - 1, 0, -1, 1), (SQ - 1, SQ - 1, -1, -1)):
            for t in (0, 1):
                img[cy + sy * t][cx + sx * i] = True
                img[cy + sy * i][cx + sx * t] = True
    return img


def selected_bitmap():
    img = blank()
    for i in range(3, SQ - 3):
        if (i // 2) % 2 == 0:
            for t in (3, 4, SQ - 5, SQ - 4):
                img[t][i] = img[i][t] = True
    return img


PTYPES = ['P', 'N', 'B', 'R', 'Q', 'K']


def sprite_list():
    """code -> bitmap. code = (p+6)*2 + dark, p in -6..6 (signed type); 26 frame, 27 corners."""
    out = {}
    for p in range(-6, 7):
        for dark in (0, 1):
            code = (p + 6) * 2 + dark
            if p == 0 and not dark:
                continue
            piece = PTYPES[abs(p) - 1] if p else None
            out[code] = square_bitmap(piece, p > 0, dark)
    out[26] = frame_bitmap()
    out[27] = corners_bitmap()
    out[28] = selected_bitmap()
    return out


def strips(img):
    """-> list of (row_offset, col_offset, bytes) with bit0 = top pixel."""
    h, w = len(img), len(img[0])
    res = []
    for j in range(0, h, 8):
        cols = []
        for x in range(w):
            b = 0
            for k in range(8):
                if j + k < h and img[j + k][x]:
                    b |= 1 << k
            cols.append(b)
        nz = [i for i, b in enumerate(cols) if b]
        if not nz:
            continue
        a, z = nz[0], nz[-1]
        res.append((j, a, bytes(cols[a:z + 1])))
    return res


